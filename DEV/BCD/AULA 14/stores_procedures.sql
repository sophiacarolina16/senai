--EX 10 - PROCEDURE COM REGRA DE NEGOCIO E REGISTRO DE PEDIDO

DELIMITER $$

CREATE PROCEDURE REGISTRAR_PEDIDO (
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;
    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )

    VALUES(
        P_ID_CLIENTE,NOW(), 'ABERTO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();
    COMMIT;

END $$

DELIMITER;

CALL REGISTRAR_PEDIDO(1,@PEDIDO);

SELECT @PEDIDO;



