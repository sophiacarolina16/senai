-- Criar tabelas - Usuario, Livro, Emprestimo, Categoria, Fornecedor

DROP DATABASE IF EXISTS BIBLIOTECA_SENAI_SOPHIA;

CREATE DATABASE IF NOT EXISTS BIBLIOTECA_SENAI_SOPHIA;
USE BIBLIOTECA_SENAI_SOPHIA;

CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    CIDADE VARCHAR(80),
    ATIVO BOOLEAN DEFAULT TRUE,
    CONSTRAINT PK_USUARIO PRIMARY KEY(ID_USUARIO),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    NOME VARCHAR(80) NOT NULL UNIQUE,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY(ID_CATEGORIA)
);

CREATE TABLE LIVRO (
    ID_LIVRO INT AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 
    CHECK (QUANTIDADE_DISPONIVEL >= 0),
    ID_CATEGORIA INT NOT NULL,
    CONSTRAINT PK_LIVRO PRIMARY KEY(ID_LIVRO),
    CONSTRAINT UQ_ISBN UNIQUE (ISBN),
    CONSTRAINT FK_CATEGORIA_LIVRO FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA)
);

CREATE TABLE EMPRESTIMO (
    ID_EMPRESTIMO INT AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) 
    DEFAULT 'ABERTO' CHECK (STATUS_EMPRESTIMO IN ('ABERTO', 'DEVOLVIDO', 'ATRASADO')),
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT PK_EMPRESTIMO PRIMARY KEY(ID_EMPRESTIMO),
    CONSTRAINT FK_USUARIO_EMPRESTIMO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_LIVRO_EMPRESTIMO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO(ID_LIVRO) ON DELETE CASCADE ON UPDATE CASCADE
);


CREATE TABLE FORNECEDOR (
    ID_FORNECEDOR INT AUTO_INCREMENT,
    CNPJ CHAR(14) NOT NULL UNIQUE,
    RAZAO_SOCIAL VARCHAR(80) NOT NULL,
    CONSTRAINT PK_FORNECEDOR PRIMARY KEY(ID_FORNECEDOR),
    CONSTRAINT UQ_CNPJ UNIQUE (CNPJ)
);

